import CoreAudio
import Foundation

enum Wave3V3AudioDSPAndRoutingContract {
    static func run(_ suite: TestSuite) {
        testAutoEQCatalogPresetsAndSearch(suite)
        testAutoEQProfileParserAPOAndClamping(suite)
        testFletcherMunsonLoudnessAndBiquadDSP(suite)
        testAudioChainRoutingAndUIContracts(suite)
    }

    private static func testAutoEQCatalogPresetsAndSearch(_ suite: TestSuite) {
        let presets = MixerAutoEQCatalog.presets
        suite.expect(presets.count >= 16, "MixerAutoEQCatalog exposes at least 16 headphone/speaker presets")

        let uniqueIDs = Set(presets.map(\.id))
        suite.expect(uniqueIDs.count == presets.count, "MixerAutoEQCatalog preset IDs are unique")

        suite.expect(presets.allSatisfy { $0.gainsDB.count == MixerEQPreset.isoFrequenciesHz.count },
                     "All AutoEQ presets provide 10 ISO band gains")

        let hd600 = MixerAutoEQCatalog.preset(id: "autoeq-sennheiser-hd600")
        suite.expect(hd600 != nil && hd600?.name.contains("HD 600") == true,
                     "MixerAutoEQCatalog resolves preset by ID")

        let airpodsMatches = MixerAutoEQCatalog.search("airpods")
        suite.expect(airpodsMatches.count >= 2, "MixerAutoEQCatalog search matches multiple AirPods profiles")
    }

    private static func testAutoEQProfileParserAPOAndClamping(_ suite: TestSuite) {
        let apoText = """
        # Generated by AutoEQ
        Preamp: -4.2 dB
        Filter 1: ON LSC Fc 105 Hz Gain 5.5 dB Q 0.70
        Filter 2: ON PK Fc 250 Hz Gain -2.5 dB Q 1.41
        Filter 3: ON PK Fc 2000 Hz Gain 3.0 dB Q 2.00
        Filter 4: OFF PK Fc 5000 Hz Gain 6.0 dB Q 1.00
        Filter 5: ON HSC Fc 9000 Hz Gain -1.5 dB Q 0.71
        """
        let parsed = AutoEQProfileParser.parseEqualizerAPO(apoText, name: "Custom Test HP")
        suite.expect(parsed != nil, "AutoEQProfileParser parses standard EqualizerAPO ParametricEQ text")
        if let parsed {
            suite.expect(parsed.name == "Custom Test HP", "Parsed preset retains requested name")
            suite.expect(abs(parsed.preampDB - (-4.2)) < 0.05, "Parsed preset retains clamped preamp gain")
            suite.expect(parsed.gainsDB.count == 10 && parsed.gainsDB.allSatisfy { $0 >= -15 && $0 <= 15 && $0.isFinite },
                         "Parsed preset projects active filters cleanly onto 10 bounded ISO gains")
        }

        let extremeText = """
        Preamp: -40.0 dB
        Filter 1: ON PK Fc 5 Hz Gain 45.0 dB Q 0.01
        """
        let clamped = AutoEQProfileParser.parseEqualizerAPO(extremeText, name: "Extreme")
        suite.expect(clamped != nil, "AutoEQProfileParser clamps out-of-range frequency/gain/preamp values instead of dropping")
        if let clamped {
            suite.expect(clamped.preampDB >= -12 && clamped.preampDB <= 12,
                         "Extreme preamp dB is clamped within +/-12 dB")
        }

        let emptyInvalid = AutoEQProfileParser.parseEqualizerAPO("Filter 1: OFF PK Fc 1000 Hz Gain 3 dB Q 1.0", name: "Disabled")
        suite.expect(emptyInvalid == nil, "AutoEQProfileParser returns nil when no ON filters exist")
    }

    private static func testFletcherMunsonLoudnessAndBiquadDSP(_ suite: TestSuite) {
        let disabled = FletcherMunsonLoudness.compensationGains(volume: 0.1, enabled: false)
        suite.expect(disabled.lowShelfDB == 0 && disabled.highShelfDB == 0,
                     "Loudness compensation returns 0 dB when disabled")

        let unity = FletcherMunsonLoudness.compensationGains(volume: 1.0, enabled: true)
        suite.expect(abs(unity.lowShelfDB) < 0.001 && abs(unity.highShelfDB) < 0.001,
                     "Loudness compensation returns 0 dB at full unity volume")

        let quiet = FletcherMunsonLoudness.compensationGains(volume: 0.2, enabled: true)
        let whisper = FletcherMunsonLoudness.compensationGains(volume: 0.0, enabled: true)
        suite.expect(quiet.lowShelfDB > 4.0 && whisper.lowShelfDB >= quiet.lowShelfDB && quiet.highShelfDB > 2.0,
                     "Fletcher-Munson loudness boosts low/high shelves monotonically as volume drops")

        let nanSafe = FletcherMunsonLoudness.compensationGains(volume: .nan, enabled: true)
        suite.expect(nanSafe.lowShelfDB == 0 && nanSafe.highShelfDB == 0,
                     "Loudness compensation guards NaN volume cleanly")

        let biquad = FletcherMunsonLoudness.LoudnessBiquadProcessor()
        biquad.update(volume: 0.15, enabled: true, sampleRate: 48_000)

        let frames = 256
        var left = [Float](repeating: 0, count: frames)
        var right = [Float](repeating: 0, count: frames)
        for i in 0..<frames {
            let phase = Float(i) * 2 * Float.pi * 80 / 48_000
            left[i] = sin(phase) * 0.25
            right[i] = (i == 12) ? Float.nan : sin(phase) * 0.25
        }
        left.withUnsafeMutableBufferPointer { lb in
            right.withUnsafeMutableBufferPointer { rb in
                if let lp = lb.baseAddress, let rp = rb.baseAddress {
                    let ptrs: [UnsafeMutablePointer<Float>] = [lp, rp]
                    ptrs.withUnsafeBufferPointer { channelBufs in
                        if let base = channelBufs.baseAddress {
                            biquad.process(channelCount: 2, frames: frames, channels: base)
                        }
                    }
                }
            }
        }
        suite.expect(left.allSatisfy(\.isFinite) && right.allSatisfy(\.isFinite),
                     "LoudnessBiquadProcessor sanitizes NaN samples and outputs finite audio")
    }

    private static func testAudioChainRoutingAndUIContracts(_ suite: TestSuite) {
        let host = (try? String(contentsOfFile: "Sources/Vorssaint/Services/Audio/MixerAudioUnitHost.swift", encoding: .utf8)) ?? ""
        let mixer = (try? String(contentsOfFile: "Sources/Vorssaint/Services/Audio/AppVolumeMixer.swift", encoding: .utf8)) ?? ""
        let section = (try? String(contentsOfFile: "Sources/Vorssaint/UI/MenuPanel/MixerSection.swift", encoding: .utf8)) ?? ""
        let notchMixer = (try? String(contentsOfFile: "Sources/Vorssaint/UI/Notch/NotchMixerView.swift", encoding: .utf8)) ?? ""

        suite.expect(host.contains("MixerRealtimeAUChainProcessor")
                     && host.contains("chainSlots")
                     && host.contains("os_unfair_lock_trylock")
                     && host.contains("slotCount = 3"),
                     "MixerAudioUnitHost implements lock-free 3-slot MixerRealtimeAUChainProcessor")

        suite.expect(mixer.contains("postEQProcessor")
                     && mixer.contains("loudnessEnabled")
                     && mixer.contains("applyAutoEQPreset"),
                     "AppVolumeMixer wires postEQProcessor hook, loudness toggle, and AutoEQ preset application")

        suite.expect(section.contains("OverhaulV3Strings.audioChainTitle")
                     && section.contains("OverhaulV3Strings.perAppOutputTitle")
                     && section.contains("OverhaulV3Strings.autoEQTitle")
                     && section.contains("OverhaulV3Strings.loudnessToggleTitle")
                     && !section.contains(".toggleStyle(.switch)")
                     && !section.contains(".toggleStyle(.checkbox)"),
                     "MixerSection exposes 3-slot AU chain, per-app output, AutoEQ, and loudness with VorssaintDesignKit")

        suite.expect(!notchMixer.contains(".toggleStyle(.switch)")
                     && !notchMixer.contains(".toggleStyle(.checkbox)"),
                     "NotchMixerView uses VorssaintDesignKit without raw switches or checkboxes")
    }
}
